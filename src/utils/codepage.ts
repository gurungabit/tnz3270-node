// ---------------------------------------------------------------------------
// Code page registry
// ---------------------------------------------------------------------------

interface CodePageTable {
  decodeTable: number[];
  encodeTable: Map<number, number>;
}

/** Build a reverse encode map from a decode table. */
function buildEncodeTable(decodeTable: number[]): Map<number, number> {
  const map = new Map<number, number>();
  for (let i = 0; i < decodeTable.length; i++) {
    const codePoint = decodeTable[i];
    if (codePoint !== 0xfffd && !map.has(codePoint)) {
      map.set(codePoint, i);
    }
  }
  return map;
}

/** Built-in code page tables. */
const BUILTIN_TABLES: Record<string, number[]> = {
  cp037: CP037_TO_UNICODE,
  cp1047: CP1047_TO_UNICODE,
  cp310: CP310_TO_UNICODE,
};

/** Cache of compiled code page tables (built on first use). */
const compiledTables = new Map<string, CodePageTable>();

/** Get or compile a code page table. */
function getTable(name: string): CodePageTable | undefined {
  const cached = compiledTables.get(name);
  if (cached) return cached;

  const decodeTable = BUILTIN_TABLES[name];
  if (!decodeTable) return undefined;

  const table: CodePageTable = {
    decodeTable,
    encodeTable: buildEncodeTable(decodeTable),
  };
  compiledTables.set(name, table);
  return table;
}

// ---------------------------------------------------------------------------
// Special byte translations for screen display
// ---------------------------------------------------------------------------

/**
 * EBCDIC control bytes that should display as spaces.
 */
const DC_TO_DISPLAY: ReadonlyMap<number, number> = new Map([
  [0x00, 0x40], // NULL -> space
  [0x0c, 0x40], // FF -> space
  [0x0d, 0x40], // CR -> space
  [0x15, 0x40], // NL -> space
  [0x19, 0x40], // EM -> space
  [0xff, 0x40], // EO -> space
]);

/**
 * Special EBCDIC control characters with Unicode display representations.
 */
const SPECIAL_DISPLAY_CHARS: ReadonlyMap<number, number> = new Map([
  [0x1a, 0x2218], // SUB -> solid circle
  [0x1c, 0x2611], // DUP -> check-mark
  [0x1e, 0x2612], // FM  -> x-mark
]);

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/**
 * Extract the numeric code page ID from an encoding name.
 * E.g. "cp037" -> 37, "cp1047" -> 1047
 */
function extractCodePageNumber(encoding: string): number {
  const match = encoding.match(/(\d+)$/);
  if (!match) {
    throw new Error(
      `Encoding '${encoding}' does not end in a code page number`,
    );
  }
  return parseInt(match[1], 10);
}

/**
 * Create a CodecEntry for the given encoding name.
 *
 * Built-in encodings: cp037 (US EBCDIC), cp1047 (z/OS), cp310 (APL).
 * Additional code pages can be registered with {@link registerCodePage}.
 *
 * @throws {Error} if the encoding is not supported
 */
export function getCodec(encoding: string): CodecEntry {
  const normalized = encoding.toLowerCase().replace('-', '');
  const table = getTable(normalized);

  if (!table) {
    throw new Error(`Unsupported encoding: ${encoding}`);
  }

  const codePageNumber = extractCodePageNumber(normalized);

  return {
    name: normalized,
    codePageNumber,
    encode(str: string): Buffer {
      const bytes: number[] = [];
      for (const char of str) {
        const codePoint = char.codePointAt(0)!;
        const byte = table.encodeTable.get(codePoint);
        bytes.push(byte !== undefined ? byte : 0x3f); // 0x3f = SUB
      }
      return Buffer.from(bytes);
    },
    decode(buf: Buffer): string {
      const chars: string[] = [];
      for (let i = 0; i < buf.length; i++) {
        chars.push(String.fromCodePoint(table.decodeTable[buf[i]]));
      }
      return chars.join('');
    },
  };
}

/**
 * Check if an encoding is supported.
 */
export function isEncodingSupported(encoding: string): boolean {
  const normalized = encoding.toLowerCase().replace('-', '');
  return normalized in BUILTIN_TABLES;
}

/**
 * Register a custom code page.
 *
 * @param name - Code page name (e.g. "cp500")
 * @param decodeTable - Array of 256 Unicode code points
 */
export function registerCodePage(
  name: string,
  decodeTable: number[],
): void {
  if (decodeTable.length !== 256) {
    throw new Error('Decode table must have exactly 256 entries');
  }
  const normalized = name.toLowerCase().replace('-', '');
  BUILTIN_TABLES[normalized] = decodeTable;
  compiledTables.delete(normalized); // invalidate cache
}

/**
 * Translate raw EBCDIC data-character bytes into displayable bytes.
 * Replaces control characters (NULL, FF, CR, NL, EM, EO) with
 * EBCDIC space (0x40) so they render as blanks.
 */
export function translateDataToDisplay(data: Uint8Array): Uint8Array {
  const result = new Uint8Array(data.length);
  for (let i = 0; i < data.length; i++) {
    const replacement = DC_TO_DISPLAY.get(data[i]);
    result[i] = replacement !== undefined ? replacement : data[i];
  }
  return result;
}

/**
 * Get the Unicode display character for a special EBCDIC control byte.
 * Returns undefined if the byte is not a special display character.
 */
export function getSpecialDisplayChar(byte: number): string | undefined {
  const codePoint = SPECIAL_DISPLAY_CHARS.get(byte);
  if (codePoint !== undefined) {
    return String.fromCodePoint(codePoint);
  }
  return undefined;
}
